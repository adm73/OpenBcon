ALTER TABLE companies
  DROP CONSTRAINT IF EXISTS companies_created_by_fkey,
  DROP CONSTRAINT IF EXISTS companies_updated_by_fkey,
  ADD COLUMN created_by_numeric bigint,
  ADD COLUMN updated_by_numeric bigint;
UPDATE companies AS companies
SET created_by_numeric = created_mapping.new_id
FROM app_user_id_map AS created_mapping
WHERE companies.created_by = created_mapping.old_id;
UPDATE companies AS companies
SET updated_by_numeric = mapping.new_id
FROM app_user_id_map AS mapping
WHERE companies.updated_by = mapping.old_id;
ALTER TABLE companies DROP COLUMN created_by;
ALTER TABLE companies DROP COLUMN updated_by;
ALTER TABLE companies RENAME COLUMN created_by_numeric TO created_by;
ALTER TABLE companies RENAME COLUMN updated_by_numeric TO updated_by;
ALTER TABLE companies
  ADD CONSTRAINT companies_created_by_fkey
  FOREIGN KEY (created_by) REFERENCES app_users(numeric_id) ON DELETE SET NULL,
  ADD CONSTRAINT companies_updated_by_fkey
  FOREIGN KEY (updated_by) REFERENCES app_users(numeric_id) ON DELETE SET NULL;

ALTER TABLE funding_programs
